function getQuestTextForLevel(level, mainCharacter) {
  if (level === 1) {
    const c = (typeof CHARACTERS !== 'undefined') ? CHARACTERS[mainCharacter] : null;
    return c ? c.firstQuest : LEVEL_QUESTS[2];
  }
  return LEVEL_QUESTS[level] || 'さらなる高みを目指しましょう（クエストは準備中です）';
}
